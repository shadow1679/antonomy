"""Generate the 64-entry cos/sin lookup tables in Q8 fixed point.

Writes sim/tables.json (read by Python and JS) and sim/rust/src/tables.rs (the
Rust copy). Run once; the output is committed and used by every implementation,
so no implementation ever calls a float trig function.
"""
import json
import math
import os

N = 64


def q8(x):
    return int(math.floor(x * 256 + 0.5))


tables = {
    "cos64": [q8(math.cos(2 * math.pi * k / N)) for k in range(N)],
    "sin64": [q8(math.sin(2 * math.pi * k / N)) for k in range(N)],
}

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tables.json")
with open(out, "w") as f:
    json.dump(tables, f)
    f.write("\n")
print("wrote", out)

rs = os.path.join(os.path.dirname(os.path.abspath(__file__)), "rust", "src", "tables.rs")
with open(rs, "w") as f:
    f.write("// Generated by sim/gen_tables.py. Do not edit.\n\n")
    for name, key in (("COS64", "cos64"), ("SIN64", "sin64")):
        f.write("pub const %s: [i32; %d] = [\n" % (name, N))
        for i in range(0, N, 16):
            f.write("    " + ", ".join(str(v) for v in tables[key][i:i + 16]) + ",\n")
        f.write("];\n\n")
print("wrote", rs)
